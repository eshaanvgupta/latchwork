'use client';

import { useState } from 'react';
import { Play, Terminal, Shield, Copy } from 'lucide-react';
import { GATEWAY_URL } from '@/lib/endpoints';

export default function PlaygroundPage() {
  const [serviceSlug, setServiceSlug] = useState('latchwork-test-service');
  const [apiKey, setApiKey] = useState('');
  const [method, setMethod] = useState('GET');
  const [path, setPath] = useState('/api/data');
  const [body, setBody] = useState('{"query":"example"}');
  const [loading, setLoading] = useState(false);
  const [response, setResponse] = useState<any>(null);
  const [receipt, setReceipt] = useState<any>(null);
  const [history, setHistory] = useState<number[]>([]);
  const [error, setError] = useState('');

  const send = async () => {
    setError(''); setResponse(null); setReceipt(null);
    if (!GATEWAY_URL) { setError('This preview has no gateway configured. Run the local stack or rebuild with NEXT_PUBLIC_GATEWAY_URL.'); return; }
    if (!apiKey) { setError('Enter a real gateway key from your agreement.'); return; }
    if (!/^[a-zA-Z0-9_-]+$/.test(serviceSlug)) { setError('Enter a valid service slug.'); return; }
    if (!path.startsWith('/') || path.startsWith('//')) { setError('Use a relative upstream path beginning with /.'); return; }
    if (method === 'POST') { try { JSON.parse(body); } catch { setError('Request body must be valid JSON.'); return; } }
    setLoading(true);
    const start = performance.now();
    try {
      const result = await fetch(`${GATEWAY_URL}/v1/service/${encodeURIComponent(serviceSlug)}${path}`, {
        method, headers: { 'X-Latchwork-Key': apiKey, 'Content-Type': 'application/json' },
        body: method === 'POST' ? body : undefined, signal: AbortSignal.timeout(15000),
      });
      const elapsed = Math.round(performance.now() - start);
      const text = await result.text();
      let payload; try { payload = JSON.parse(text); } catch { payload = text; }
      setResponse({ status: result.status, browserRoundTripMs: elapsed, body: payload });
      setHistory(previous => [...previous.slice(-9), elapsed]);
      const receiptId = result.headers.get('x-latchwork-receipt-id');
      const signature = result.headers.get('x-latchwork-receipt-signature');
      if (receiptId) {
        let record: unknown = null;
        try {
          const receiptResponse = await fetch(`${GATEWAY_URL}/v1/receipts/${encodeURIComponent(receiptId)}`, { headers: { 'X-Latchwork-Key': apiKey }, signal: AbortSignal.timeout(4000) });
          if (receiptResponse.ok) record = await receiptResponse.json();
        } catch { /* The returned receipt headers remain visible if lookup fails. */ }
        setReceipt({ receiptId, signature, gatewayRequestId: result.headers.get('x-latchwork-request-id'), gatewayLatencyMs: result.headers.get('x-latchwork-latency-ms'), record, verification: 'Signature returned by gateway; not independently verified by this UI. No circuit evaluation or settlement implied.' });
      }
      if (!result.ok) setError(`Gateway returned HTTP ${result.status}. See the response for details.`);
    } catch (failure) { setError(failure instanceof Error ? failure.message : 'Request failed. No receipt was generated by this UI.'); }
    finally { setLoading(false); }
  };

  const input = 'w-full rounded-lg border border-white/10 bg-black/30 px-3 py-2 font-mono text-sm text-zinc-200';
  return <div className="page-shell space-y-7">
    <div className="page-heading"><div className="text-xs font-mono text-amber-400 flex items-center gap-2 mb-2"><Terminal className="h-4 w-4" /> DEVELOPER PLAYGROUND</div><h1 className="font-display text-3xl font-bold leading-tight sm:text-4xl">Send an authenticated request</h1><p className="text-sm text-zinc-400 mt-3">Forwards real traffic through your configured gateway. Receipts are separate from witness reports and settlement authorization.</p></div>
    <div className="grid items-start gap-5 lg:grid-cols-2"><section className="content-panel p-5 space-y-4 sm:p-6">
      <p className="text-xs font-mono text-zinc-500 break-all">Gateway: {GATEWAY_URL}</p>
      <label className="block text-sm text-zinc-400">Service slug<input className={`${input} mt-2`} value={serviceSlug} onChange={event => setServiceSlug(event.target.value)} /></label>
      <label className="block text-sm text-zinc-400">Gateway API key<input type="password" autoComplete="off" className={`${input} mt-2`} value={apiKey} onChange={event => setApiKey(event.target.value)} placeholder="lw_live_…" /></label>
      <div className="flex gap-2"><select aria-label="HTTP method" className="rounded-lg bg-zinc-900 border border-white/10 px-3" value={method} onChange={event => setMethod(event.target.value)}><option>GET</option><option>POST</option></select><input aria-label="Upstream request path" className={input} value={path} onChange={event => setPath(event.target.value)} /></div>
      {method === 'POST' && <label className="block text-sm text-zinc-400">JSON body<textarea className={`${input} mt-2 h-32`} value={body} onChange={event => setBody(event.target.value)} /></label>}
      <button disabled={loading} onClick={send} className="flex gap-2 items-center rounded-xl bg-amber-400 px-4 py-3 text-black font-semibold text-sm disabled:opacity-50"><Play className="h-4 w-4" />{loading ? 'Sending…' : 'Send request'}</button>
      {error && <p role="alert" className="text-sm text-rose-400 break-all">{error}</p>}
      <p className="text-xs text-zinc-500">Last browser round trips: {history.length ? history.map(value => `${value} ms`).join(' · ') : 'No requests sent.'}</p>
    </section><section className="content-panel p-5 space-y-4 sm:p-6">
      <div className="flex justify-between items-center"><h2 className="font-semibold">Gateway response</h2>{response && <button aria-label="Copy response" onClick={() => navigator.clipboard.writeText(JSON.stringify(response, null, 2))}><Copy className="h-4 w-4 text-zinc-400" /></button>}</div>
      <pre className="rounded-lg bg-black/30 p-4 font-mono text-xs text-zinc-300 whitespace-pre-wrap break-all min-h-36 max-h-80 overflow-auto">{response ? JSON.stringify(response, null, 2) : 'No response yet.'}</pre>
      <h2 className="font-semibold flex gap-2 items-center"><Shield className="h-4 w-4 text-indigo-400" /> Receipt returned by gateway</h2>
      <pre className="rounded-lg bg-black/30 p-4 font-mono text-xs text-zinc-300 whitespace-pre-wrap break-all max-h-96 overflow-auto">{receipt ? JSON.stringify(receipt, null, 2) : 'No signed receipt received.'}</pre>
    </section></div>
  </div>;
}

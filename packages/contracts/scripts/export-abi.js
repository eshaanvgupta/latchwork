import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const contractsToExport = [
  'AgreementFactory',
  'SettlementVault',
  'SettlementEngine',
  'CircuitPolicyRegistry',
  'WitnessRegistry',
  'DisputeController',
  'ProtocolTreasury',
  'MockUSDC',
  'MockTapeOutProcessor'
];

const outDir = path.resolve(__dirname, '../out');
const tsDir = path.resolve(__dirname, '../src_ts');

if (!fs.existsSync(tsDir)) {
  fs.mkdirSync(tsDir, { recursive: true });
}

let tsContent = `// Automatically generated by export-abi.js\n\n`;

for (const name of contractsToExport) {
  const artifactPath = path.join(outDir, `${name}.sol`, `${name}.json`);
  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'));
    tsContent += `export const ${name}ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n`;
    tsContent += `export const ${name}Bytecode = '${artifact.bytecode.object}' as const;\n\n`;
  }
}

fs.writeFileSync(path.join(tsDir, 'index.ts'), tsContent);
console.log('Contract ABIs exported successfully to src_ts/index.ts');

